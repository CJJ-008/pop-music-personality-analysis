def kb(key: str, label: str = "❓") -> None:
    """渲染一个问号说明按钮（st.popover），点击弹出通俗解释。"""
    item = GLOSSARY[key]
    with st.popover(label, help=f"点开看通俗解释：{item['title']}"):
        st.markdown(f"**📖 {item['title']}**")
        st.caption(item["tagline"])
        st.markdown("\n\n".join(item["body"]))


def head_kb(title: str, *keys: str, bold: bool = False) -> None:
    """标题与问号按钮同一行：标题占宽列，每个知识点占一个窄列。"""
    cols = st.columns([9] + [1] * len(keys))
    with cols[0]:
        st.markdown(f"**{title}**") if bold else st.subheader(title)
    for col, key in zip(cols[1:], keys):
        with col:
            kb(key)


def kb_row(*keys: str, label: str = "📖 名词小课堂") -> None:
    """一行「小课堂」：说明文字 + 若干问号按钮，用于没有现成标题的位置。"""
    cols = st.columns([9] + [1] * len(keys))
    with cols[0]:
        st.caption(label)
    for col, key in zip(cols[1:], keys):
        with col:
            kb(key)
